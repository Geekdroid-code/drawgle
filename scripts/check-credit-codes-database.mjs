// Isolated PostgreSQL engine tests for launch credit codes.
// Pass the package.json path of a temporary PGlite installation.
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve } from "node:path";
import { randomUUID } from "node:crypto";

const db = new (createRequire(resolve(process.argv[2] || "package.json"))("@electric-sql/pglite").PGlite)();
const [ana, ben, cai, dee, eve] = Array.from({ length: 5 }, () => randomUUID());

try {
  await db.exec(`
    do $$ begin
      if not exists(select 1 from pg_roles where rolname='anon') then create role anon; end if;
      if not exists(select 1 from pg_roles where rolname='authenticated') then create role authenticated; end if;
      if not exists(select 1 from pg_roles where rolname='service_role') then create role service_role bypassrls; end if;
    end $$;
    create schema auth;
    create table auth.users(id uuid primary key);
    create table public.credits (
      id bigint generated by default as identity primary key,
      created_at timestamptz not null default now(),
      credits numeric(10, 2) not null default 0,
      user_id uuid not null references auth.users(id) on delete cascade
    );
    create unique index credits_user_id_unique_idx on public.credits(user_id);
  `);
  await db.exec(await readFile("supabase/migrations/20261005090000_launch_credit_codes.sql", "utf8"));
  await db.exec("grant usage on schema public to anon, authenticated, service_role;");
  await db.exec("grant all on all tables in schema public to service_role;");
  for (const user of [ana, ben, cai, dee, eve]) await db.query("insert into auth.users(id) values($1)", [user]);
  await db.query("insert into public.credits(user_id, credits) values($1, 50)", [dee]);

  await db.exec(`
    insert into public.credit_codes(code, campaign, credits, max_redemptions, expires_at, disabled_at) values
      ('DG-ONE234', 'launch', 200, 1, null, null),
      ('DG-TWO234', 'launch', 200, 1, null, null),
      ('DG-OLD234', 'launch', 200, 1, now() - interval '1 minute', null),
      ('DG-OFF234', 'launch', 200, 1, null, now()),
      ('FRIENDS', 'friends', 100, 3, null, null);
  `);

  await db.exec("set role service_role");
  const redeem = async (user, code) =>
    (await db.query("select public.redeem_credit_code($1, $2) as value", [user, code])).rows[0].value;
  const balance = async (user) =>
    Number((await db.query("select credits from public.credits where user_id = $1", [user])).rows[0]?.credits ?? 0);
  const used = async (code) =>
    (await db.query("select redemption_count from public.credit_codes where code = $1", [code])).rows[0].redemption_count;

  // A single-use link: the first person gets the credits, nobody gets them twice.
  assert.deepEqual(await redeem(ana, "DG-ONE234"), { status: "redeemed", credits: 200, balance: 200 });
  assert.equal(await balance(ana), 200);
  assert.deepEqual(await redeem(ana, "DG-ONE234"), { status: "already_redeemed" });
  assert.deepEqual(await redeem(ben, "DG-ONE234"), { status: "exhausted" });
  assert.equal(await used("DG-ONE234"), 1);

  // One code per campaign: a second launch link does nothing for someone who claimed.
  assert.deepEqual(await redeem(ana, "DG-TWO234"), { status: "already_redeemed" });
  assert.equal(await used("DG-TWO234"), 0);
  assert.equal(await balance(ana), 200);

  // Typed by hand: case and surrounding spaces do not matter.
  assert.deepEqual(await redeem(ben, "  dg-two234 "), { status: "redeemed", credits: 200, balance: 200 });

  // Codes that cannot be claimed say why, and none of them grants anything.
  assert.deepEqual(await redeem(cai, "DG-OLD234"), { status: "expired" });
  assert.deepEqual(await redeem(cai, "DG-OFF234"), { status: "not_found" });
  assert.deepEqual(await redeem(cai, "DG-NOPE99"), { status: "not_found" });
  assert.deepEqual(await redeem(cai, "x"), { status: "not_found" });
  assert.deepEqual(await redeem(cai, null), { status: "not_found" });
  assert.deepEqual(await redeem(cai, "DG-ONE234; drop table credits"), { status: "not_found" });
  assert.equal(await balance(cai), 0);

  // Someone who already claimed hears that, even once the code is used up or expired.
  assert.deepEqual(await redeem(ben, "DG-TWO234"), { status: "already_redeemed" });

  // A shared code with three uses adds to an existing balance and stops at three.
  assert.deepEqual(await redeem(ana, "FRIENDS"), { status: "redeemed", credits: 100, balance: 300 });
  assert.deepEqual(await redeem(dee, "friends"), { status: "redeemed", credits: 100, balance: 150 });
  assert.deepEqual(await redeem(cai, "FRIENDS"), { status: "redeemed", credits: 100, balance: 100 });
  assert.deepEqual(await redeem(eve, "FRIENDS"), { status: "exhausted" });
  assert.equal(await used("FRIENDS"), 3);
  assert.equal(await balance(eve), 0);

  const ledger = (await db.query("select code, campaign, user_id, credits from public.credit_code_redemptions order by id")).rows;
  assert.deepEqual(
    ledger.map((row) => [row.code, row.campaign, row.user_id, Number(row.credits)]),
    [
      ["DG-ONE234", "launch", ana, 200],
      ["DG-TWO234", "launch", ben, 200],
      ["FRIENDS", "friends", ana, 100],
      ["FRIENDS", "friends", dee, 100],
      ["FRIENDS", "friends", cai, 100],
    ],
  );

  await assert.rejects(redeem(null, "FRIENDS"), /needs a user/);
  await db.exec("reset role");

  // Codes are stored in their canonical form, so lookups never miss on case.
  await assert.rejects(
    db.exec("insert into public.credit_codes(code, campaign, credits) values ('dg-lower', 'launch', 200)"),
    /credit_codes_code_format/,
  );
  await assert.rejects(
    db.exec("insert into public.credit_codes(code, campaign, credits) values ('DG-ZERO1', 'launch', 0)"),
    /credit_codes_credits_range/,
  );

  // A signed-in browser can neither redeem directly nor read the codes.
  for (const role of ["authenticated", "anon"]) {
    await db.exec(`set role ${role}`);
    await assert.rejects(redeem(eve, "FRIENDS"), /permission denied/);
    await assert.rejects(db.query("select code from public.credit_codes"), /permission denied/);
    await assert.rejects(db.query("select code from public.credit_code_redemptions"), /permission denied/);
    await db.exec("reset role");
  }

  console.log("credit code database checks passed");
} finally {
  await db.close();
}
