create or replace function public.dismiss_deleted_screen_roadmap_item()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.project_screen_roadmap
  set generated_screen_id = null, status = 'dismissed', updated_at = timezone('utc', now())
  where generated_screen_id = old.id;
  return old;
end;
$$;

